"""Generate THIRD-PARTY-LICENSES.md from the resolved dependency graph."""
import collections
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(sys.argv[1]).resolve()

meta = json.loads(
    subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--all-features"],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout
)

workspace = {p["id"] for p in meta["packages"] if p["name"].startswith("riptide-")}

by_licence = collections.defaultdict(list)
for pkg in meta["packages"]:
    if pkg["id"] in workspace:
        continue
    licence = pkg.get("license") or "see license file in the crate"
    by_licence[licence].append((pkg["name"], pkg["version"], pkg.get("repository") or ""))

total = sum(len(v) for v in by_licence.values())

lines = [
    "# Third-party licences",
    "",
    "Riptide itself is licensed under the GNU General Public License, version 3 or later;",
    "see [LICENSE](LICENSE). It builds on the Rust crates listed below, each under its own",
    "licence. Every licence here has been checked as compatible with GPL-3.0-or-later, and CI",
    "enforces that with `cargo deny check licenses` against the allow-list in",
    "[deny.toml](deny.toml) — a dependency under an incompatible licence fails the build.",
    "",
    "Where a crate offers a choice of licences (`MIT OR Apache-2.0` and similar), Riptide",
    "relies on it under whichever of those licences you prefer; the dual offer is the crate",
    "author's, and nothing here narrows it.",
    "",
    f"This file is generated by `tools/gen_licenses.py`. {total} crates, "
    f"{len(by_licence)} distinct licence expressions.",
    "",
    "To reproduce the full licence texts locally:",
    "",
    "```bash",
    "cargo install cargo-about",
    "cargo about generate --output-file licenses.html about.hbs",
    "```",
    "",
]

for licence in sorted(by_licence, key=lambda k: (-len(by_licence[k]), k)):
    crates = sorted(by_licence[licence])
    lines.append(f"## {licence}")
    lines.append("")
    lines.append(f"{len(crates)} crate{'s' if len(crates) != 1 else ''}.")
    lines.append("")
    for name, version, repo in crates:
        entry = f"- **{name}** {version}"
        if repo:
            entry += f" — <{repo}>"
        lines.append(entry)
    lines.append("")

(ROOT / "THIRD-PARTY-LICENSES.md").write_text("\n".join(lines), encoding="utf-8")
print(f"wrote THIRD-PARTY-LICENSES.md: {total} crates, {len(by_licence)} licence expressions")
